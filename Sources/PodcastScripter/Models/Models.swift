import Foundation

/// A podcast episode being written.
struct Script: Identifiable, Codable, Hashable {
    var id = UUID()
    var name: String
    var episodeDate: Date
    /// Plain-text copy of the script, used for word counts, search and plain-text export.
    var plainText: String = ""
    /// The formatted script (RTF). Nil for scripts written before formatting existed.
    var richText: Data?
    /// Story-queue items the script was created from.
    var notes: [StoryItem] = []
    var createdAt = Date()
    var updatedAt = Date()

    var displayTitle: String {
        "\(name) - \(episodeDate.formatted(.dateTime.month(.abbreviated).day().year()))"
    }

    var wordCount: Int {
        plainText.split { $0.isWhitespace || $0.isNewline }.count
    }

    /// Estimated spoken length at ~150 words per minute.
    var estimatedMinutes: Double {
        Double(wordCount) / 150.0
    }

    // Saved field names predate the rename (the text was called "script").
    private enum CodingKeys: String, CodingKey {
        case id, name, episodeDate, richText, notes, createdAt, updatedAt
        case plainText = "script"
    }
}

enum StoryKind: String, Codable, CaseIterable {
    case xPost
    case storyNote
    case article
    case news

    var label: String {
        switch self {
        case .xPost: "X post"
        case .storyNote: "Story/Note"
        case .article: "Article"
        case .news: "News"
        }
    }

    var symbol: String {
        switch self {
        case .xPost: "bubble.left"
        case .storyNote: "note.text"
        case .article: "newspaper"
        case .news: "globe"
        }
    }
}

/// An item in the story queue — either auto-generated by the notes service or added by hand.
struct StoryItem: Identifiable, Codable, Hashable {
    var id = UUID()
    var kind: StoryKind
    var title: String
    var body: String
    var source: String?
    var url: URL?
    var createdAt = Date()
}

/// A long-running story followed across episodes (injuries, transfers, etc.).
struct TrackedStory: Identifiable, Codable, Hashable {
    var id = UUID()
    var title: String
    var latestUpdate: String = ""
    var lastUpdated = Date()
    /// What was said about it in scripts, oldest first (tagged in the editor).
    var mentions: [StoryMention] = []
    /// Rumor / reported / confirmed. Optional: most stories don't need one.
    var status: StoryStatus?
    /// Every status change, oldest first, so you can see how the story developed.
    var statusHistory: [StatusChange] = []
    /// Set when the story is wrapped up; it moves to the tracker's Resolved list.
    var resolvedAt: Date?
    /// How it ended, e.g. "Back in the lineup vs SKC".
    var resolution: String?

    var isResolved: Bool { resolvedAt != nil }

    init(id: UUID = UUID(), title: String, latestUpdate: String = "", lastUpdated: Date = Date(), mentions: [StoryMention] = [], status: StoryStatus? = nil, statusHistory: [StatusChange] = []) {
        self.id = id
        self.title = title
        self.latestUpdate = latestUpdate
        self.lastUpdated = lastUpdated
        self.mentions = mentions
        self.status = status
        self.statusHistory = statusHistory
    }

    // Written by hand so stories saved before `mentions` and `status` existed still load.
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(UUID.self, forKey: .id)
        title = try c.decode(String.self, forKey: .title)
        latestUpdate = try c.decodeIfPresent(String.self, forKey: .latestUpdate) ?? ""
        lastUpdated = try c.decodeIfPresent(Date.self, forKey: .lastUpdated) ?? Date()
        mentions = try c.decodeIfPresent([StoryMention].self, forKey: .mentions) ?? []
        status = try? c.decodeIfPresent(StoryStatus.self, forKey: .status)
        statusHistory = (try? c.decodeIfPresent([StatusChange].self, forKey: .statusHistory)) ?? []
        resolvedAt = try? c.decodeIfPresent(Date.self, forKey: .resolvedAt)
        resolution = try? c.decodeIfPresent(String.self, forKey: .resolution)
    }

    /// Sets the status, recording the change (nil clears it). No-op if unchanged.
    mutating func setStatus(_ newStatus: StoryStatus?, at date: Date = Date()) {
        guard newStatus != status else { return }
        status = newStatus
        statusHistory.append(StatusChange(status: newStatus, changedAt: date))
    }
}

/// One step in a tracked story's status history (nil = status cleared).
struct StatusChange: Codable, Hashable {
    var status: StoryStatus?
    var changedAt: Date
}

/// A passage from a script tagged as part of a tracked story.
struct StoryMention: Identifiable, Codable, Hashable {
    var id = UUID()
    var scriptID: Script.ID
    /// Copied so the history still reads well if the script is renamed or deleted.
    var scriptName: String
    var episodeDate: Date
    var excerpt: String
    /// Optional takeaway, e.g. "Expected back after the international break".
    var note: String?
    var taggedAt = Date()
    /// The passage's own mark in the script when it was tagged, if any.
    var status: StoryStatus?

    // Saved under the names used before scripts were called scripts.
    private enum CodingKeys: String, CodingKey {
        case id, episodeDate, excerpt, note, taggedAt, status
        case scriptID = "projectID"
        case scriptName = "projectName"
    }
}

/// Power rankings from the notes service's /api/rankings: one entry per source, with season history.
struct RankingsSummary: Decodable, Equatable, Sendable {
    var season: Int
    /// Every season with saved rankings, newest first.
    var seasons: [Int]
    var sources: [RankingSource]
}

struct RankingSource: Decodable, Equatable, Sendable, Identifiable {
    var id: String
    var name: String
    /// "League", "Region" or "World".
    var group: String
    /// Teams in the ranking when it's fixed (30 for MLS lists), else nil.
    var scale: Int?
    var latest: RankPoint?
    var previousRank: Int?
    var history: [RankPoint]
    var checkedAt: String?
    var error: String?

    /// Places moved since the previous ranking; positive means up.
    var change: Int? {
        guard let latest, let previousRank else { return nil }
        return previousRank - latest.rank
    }
}

struct RankPoint: Decodable, Equatable, Sendable, Identifiable {
    /// YYYY-MM-DD the ranking was published.
    var date: String
    var rank: Int
    var label: String?
    var url: URL?
    var id: String { date }

    var day: Date? { ISO8601.parse("\(date)T12:00:00Z") }
}

extension Int {
    /// "1st", "22nd", "483rd".
    var ordinal: String {
        let formatter = NumberFormatter()
        formatter.numberStyle = .ordinal
        return formatter.string(from: NSNumber(value: self)) ?? String(self)
    }
}

/// MLS tables from the notes service's /api/standings.
struct Standings: Decodable, Equatable, Sendable {
    var season: String
    var updatedAt: String
    var stale: Bool
    var conferences: [StandingsTable]
    var combined: [StandingsRow]
}

struct StandingsTable: Decodable, Equatable, Sendable, Identifiable {
    var name: String
    var rows: [StandingsRow]
    var id: String { name }
}

struct StandingsRow: Decodable, Equatable, Sendable, Identifiable {
    var rank: Int
    var team: String
    var shortName: String
    var abbreviation: String
    var logo: URL?
    var played: Int
    var wins: Int
    var draws: Int
    var losses: Int
    var goalDifference: Int
    var points: Int
    /// "playoffs" (Round One), "wild_card", or nil.
    var qualification: String?
    var id: String { abbreviation }
}

/// The club's results and fixtures from the notes service's /api/matches.
struct Matches: Decodable, Equatable, Sendable {
    var season: Int?
    var team: MatchTeam
    /// Competitions with matches this season, e.g. ["MLS", "Leagues Cup"].
    var competitions: [String]?
    var results: [Match]
    var upcoming: [Match]
    var updatedAt: String
    var stale: Bool
}

struct Match: Decodable, Equatable, Sendable, Identifiable {
    var id: String
    /// ISO 8601 kickoff time.
    var date: String
    /// "MLS", "Leagues Cup", "U.S. Open Cup" or "Concacaf Champions Cup".
    var competition: String
    /// e.g. "Regular Season", "League Phase", "Quarterfinals".
    var stage: String?
    /// e.g. "Tigres UANL win 6-5 on penalties".
    var note: String?
    var venue: String?
    var broadcast: String?
    var isHome: Bool
    var opponent: MatchTeam
    var goalsFor: Int?
    var goalsAgainst: Int?
    /// "W", "D" or "L" once played.
    var result: String?
    /// "W" or "L" when a draw went to penalties.
    var shootout: String?
    var status: String

    var kickoff: Date? { ISO8601.parse(date) ?? ISO8601.parse(date.replacingOccurrences(of: "Z", with: ":00Z")) }
}

struct MatchTeam: Decodable, Equatable, Sendable {
    var name: String?
    var shortName: String?
    var abbreviation: String?
    var logo: URL?
}

enum NewsCategory: String, Hashable, Sendable {
    case team
    case league
}

struct NewsItem: Identifiable, Hashable, Sendable {
    var id = UUID()
    var category: NewsCategory
    var headline: String
    var summary: String
    var source: String
    var publishedAt: Date
    var url: URL?

    /// How a news story is kept once it's added to a script.
    var asStoryItem: StoryItem {
        StoryItem(id: id, kind: .news, title: headline, body: summary, source: source, url: url, createdAt: publishedAt)
    }
}
