import Foundation

/// A podcast episode being written.
struct Project: Identifiable, Codable, Hashable {
    var id = UUID()
    var name: String
    var episodeDate: Date
    var script: String = ""
    /// Story-queue items the project was created from.
    var notes: [StoryItem] = []
    var createdAt = Date()
    var updatedAt = Date()

    var displayTitle: String {
        "\(name) - \(episodeDate.formatted(.dateTime.month(.abbreviated).day().year()))"
    }

    var wordCount: Int {
        script.split { $0.isWhitespace || $0.isNewline }.count
    }

    /// Estimated spoken length at ~150 words per minute.
    var estimatedMinutes: Double {
        Double(wordCount) / 150.0
    }
}

enum StoryKind: String, Codable, CaseIterable {
    case xPost
    case storyNote
    case article

    var label: String {
        switch self {
        case .xPost: "X post"
        case .storyNote: "Story/Note"
        case .article: "Article"
        }
    }

    var symbol: String {
        switch self {
        case .xPost: "bubble.left"
        case .storyNote: "note.text"
        case .article: "newspaper"
        }
    }
}

/// An item in the story queue — either auto-generated by the notes service or added by hand.
struct StoryItem: Identifiable, Codable, Hashable {
    var id = UUID()
    var kind: StoryKind
    var title: String
    var body: String
    var source: String?
    var url: URL?
    var createdAt = Date()
}

/// A long-running story followed across episodes (injuries, transfers, etc.).
struct TrackedStory: Identifiable, Codable, Hashable {
    var id = UUID()
    var title: String
    var latestUpdate: String = ""
    var lastUpdated = Date()
}

/// Reference/instruction files (style guides, show formats) available to the assistant.
struct InstructionFile: Identifiable, Codable, Hashable {
    var id = UUID()
    var name: String
    var content: String
    var addedAt = Date()
}

struct RankingEntry: Identifiable, Hashable, Sendable {
    var id: String { source }
    var source: String
    var rank: Int
    /// Positive = moved up.
    var change: Int
}

struct RankingGroup: Identifiable, Hashable, Sendable {
    var id: String { title }
    var title: String
    var entries: [RankingEntry]
}

enum NewsCategory: String, Hashable, Sendable {
    case team
    case league
}

struct NewsItem: Identifiable, Hashable, Sendable {
    var id = UUID()
    var category: NewsCategory
    var headline: String
    var summary: String
    var source: String
    var publishedAt: Date
    var url: URL?
}
